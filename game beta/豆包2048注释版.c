/* ============================================================
 * 2048 小游戏 —— C语言控制台版（带超详细注释，新手友好）
 * ------------------------------------------------------------
 * 游戏规则：
 *   1. 棋盘是 4×4 的方格，开局随机放两个数字（2 或 4）
 *   2. 按 w/a/s/d 让所有数字朝 上/左/下/右 滑动
 *   3. 两个相同的数字碰到一起，会合并成它们的和（2+2=4，4+4=8……）
 *   4. 每次有效滑动后，会在随机空位生成一个新的 2 或 4
 *   5. 目标：拼出一个 2048；如果格子全满且无法再合并，游戏结束
 *
 * 编译运行方法（在终端里执行）：
 *   gcc 2048.c -o 2048     # 编译，生成可执行文件（Windows 上是 2048.exe）
 *   ./2048                 # 运行（Windows 下直接双击 2048.exe）
 *
 * 操作按键：
 *   w / W  向上      a / A  向左
 *   s / S  向下      d / D  向右
 *   q / Q  退出
 * ============================================================ */

#include <stdio.h>   // 标准输入输出：printf 输出、scanf 输入
#include <stdlib.h>  // 标准工具库：rand 随机数、system 调用系统命令
#include <time.h>    // 时间库：time(NULL) 取当前时间，用来给随机数做种子

#define SIZE   4       // 棋盘边长：4 行 × 4 列
#define TARGET 2048    // 获胜目标数字

/* ---------- 全局变量：程序里所有函数都能直接使用 ---------- */
int board[SIZE][SIZE]; // 棋盘数据，board[行][列]，值为 0 表示空格
int score = 0;         // 当前总分，每次合并都会加分

/* ---------- 函数声明（提前告诉编译器后面会有这些函数） ---------- */
void init();              // 把棋盘全部清成 0
void spawn();             // 在随机一个空格里生成 2 或 4
void draw();              // 把棋盘画到屏幕上
int  move_left();         // 核心：所有格子向左滑动并合并，返回是否真的动了
int  move_right();        // 向右滑动
int  move_up();           // 向上滑动
int  move_down();         // 向下滑动
void reverse_row(int r);  // 把第 r 行的数字顺序反过来（右移的辅助函数）
void transpose();         // 把棋盘行列互换（上下移动的辅助函数）
int  game_over();         // 判断是否已经无路可走
int  has_2048();          // 判断是否已经拼出 2048

/* ============================================================
 * main 函数：程序入口，游戏主流程都在这里
 * ============================================================ */
int main()
{
    char cmd;   // 存放用户每次按下的按键
    int moved;  // 记录本次滑动是否真的发生了变化

    /* 用当前时间做"随机种子"。
     * 如果不设种子，rand() 每次运行生成的随机数序列都是一样的，
     * 那就每次开局都是同样的局面了。 */
    srand((unsigned)time(NULL));

    init();    // 棋盘清零
    spawn();   // 随机放一个 2 或 4
    spawn();   // 再放一个，开局一共两个数字

    /* 游戏主循环：只要不退出，就不断"画棋盘 -> 检查状态 -> 等输入 -> 移动" */
    while (1)
    {
        draw();   // 第一步：把当前棋盘显示出来

        /* 第二步：检查胜负条件 */
        if (has_2048())              // 已经拼出 2048 了？
        {
            printf("\n恭喜！你拼出了 2048！\n");
            break;                   // break 跳出 while 循环，游戏结束
        }
        if (game_over())             // 没空格可走、也不能合并了？
        {
            printf("\n游戏结束！所有格子已满，且无法再合并。\n");
            break;
        }

        /* 第三步：读取用户的按键 */
        printf("请输入方向 (w=上 a=左 s=下 d=右，q=退出)：");
        scanf(" %c", &cmd);
        /* 注意 %c 前面有个空格：
         * 它会跳过上一次输入按回车时留在缓冲区里的 '\n'，
         * 否则 %c 会把回车当成一个字符读进来。 */

        /* 第四步：根据按键，调用对应的移动函数 */
        switch (cmd)
        {
            case 'w': case 'W':  moved = move_up();    break;  // 上
            case 's': case 'S':  moved = move_down();  break;  // 下
            case 'a': case 'A':  moved = move_left();  break;  // 左
            case 'd': case 'D':  moved = move_right(); break;  // 右
            case 'q': case 'Q':  printf("再见，欢迎再玩！\n");
                                 return 0;   // return 直接结束 main，退出程序
            default:             // 其他按键
                printf("无效按键！请按 w/a/s/d，或 q 退出。\n");
                moved = 0;       // 无效按键不算移动，不生成新数字
                break;
        }

        /* 第五步：只有当棋盘真的发生了变化，才生成新数字 */
        if (moved)
            spawn();
    }

    return 0;   // 程序正常结束
}

/* ============================================================
 * init：把棋盘所有格子清零
 * ============================================================ */
void init()
{
    int r, c;   // 行、列循环变量
    for (r = 0; r < SIZE; r++)      // 遍历每一行
        for (c = 0; c < SIZE; c++)  // 遍历每一列
            board[r][c] = 0;        // 全部置 0
}

/* ============================================================
 * spawn：在随机一个空格里生成新数字（90% 是 2，10% 是 4）
 * ============================================================ */
void spawn()
{
    int empty[SIZE * SIZE][2];  // 记录所有空格的位置：[序号][0]是行，[1]是列
    int count = 0;              // 空格的数量
    int r, c, i;

    /* 第 1 步：找出所有空格，存进 empty 数组 */
    for (r = 0; r < SIZE; r++)
        for (c = 0; c < SIZE; c++)
            if (board[r][c] == 0)
            {
                empty[count][0] = r;
                empty[count][1] = c;
                count++;
            }

    if (count == 0)   // 一个空格都没有，没法生成，直接返回
        return;

    /* 第 2 步：随机挑一个空格，放数字 */
    i = rand() % count;   // rand() 产生随机数，% count 取余得到 0 ~ count-1
    /* (rand() % 10 == 0) 只有 1/10 概率成立：成立放 4，否则放 2 */
    board[empty[i][0]][empty[i][1]] = (rand() % 10 == 0) ? 4 : 2;
}

/* ============================================================
 * draw：把棋盘画到屏幕上
 * ============================================================ */
void draw()
{
    int r, c;

    /* 清屏：让画面保持干净。Windows 用 cls，Linux/Mac 用 clear */
#ifdef _WIN32
    system("cls");
#else
    system("clear");
#endif

    printf("======== 2048 ========   分数：%d\n", score);
    printf("按键：w上  a左  s下  d右  q退出\n\n");

    /* 一行一行地打印，点号 . 代表空格子 */
    for (r = 0; r < SIZE; r++)
    {
        for (c = 0; c < SIZE; c++)
        {
            if (board[r][c] == 0)
                printf("%6c", '.');
            /* %6c：让字符占 6 个字符的宽度，这样所有格子能上下对齐 */
            else
                printf("%6d", board[r][c]);
        }
        printf("\n\n");   // 行与行之间空一行，更像方块棋盘
    }
    printf("\n");
}

/* ============================================================
 * move_left：所有格子向左滑动 + 合并（核心函数！）
 * 返回 1 表示棋盘发生了变化，返回 0 表示按了但什么都没变
 * 其他三个方向的移动，都是通过"变形"借用这个函数实现的
 * ============================================================ */
int move_left()
{
    int moved = 0;  // 标记：这一轮是否真的动了
    int r, c, pos;

    for (r = 0; r < SIZE; r++)   // 逐行处理
    {
        /* ---- 第 1 步：把这一行的数字全部"挤"到左边 ----
         * 例如 [0, 2, 0, 4]  ->  [2, 4, 0, 0]               */
        pos = 0;   // pos 指向下一个要放置数字的位置（从最左边开始）
        for (c = 0; c < SIZE; c++)
        {
            if (board[r][c] != 0)        // 找到一个非零数字
            {
                if (pos != c)            // 它的位置还不是最靠左的空位，说明要挪
                {
                    board[r][pos] = board[r][c];  // 把数字挪到左边
                    board[r][c] = 0;              // 原来的位置清空
                    moved = 1;                    // 记录：发生了移动
                }
                pos++;                   // 下一个数字放到更靠左一格
            }
        }

        /* ---- 第 2 步：相邻的相同数字合并 ----
         * 例如 [2, 2, 2, 2]  ->  从左往右合并成 [4, 0, 4, 0]
         * 注意：一个数字每一轮只能合并一次（不能 2->4->8 连跳），
         * 所以合并后要 c++ 跳过被吃掉的那个格子。             */
        for (c = 0; c < SIZE - 1; c++)
        {
            if (board[r][c] != 0 && board[r][c] == board[r][c + 1])
            {
                board[r][c] *= 2;        // 左边的数字 ×2（2 变 4，4 变 8……）
                score += board[r][c];    // 分数加上合并出来的数字
                board[r][c + 1] = 0;     // 右边的数字消失
                moved = 1;               // 发生了合并，也算"动了"
                c++;                     // 跳过被吃掉的那个格子
            }
        }

        /* ---- 第 3 步：合并后中间会留下空格，再挤一次 ----
         * 例如上一步得到 [4, 0, 4, 0]  ->  [4, 4, 0, 0]       */
        pos = 0;
        for (c = 0; c < SIZE; c++)
            if (board[r][c] != 0)
                board[r][pos++] = board[r][c];   // 非零数字依次排到左边
        for (; pos < SIZE; pos++)                // 剩下的位置补 0
            board[r][pos] = 0;
    }

    return moved;   // 告诉调用者：这次有没有真的动
}

/* ============================================================
 * reverse_row：把第 r 行的数字顺序颠倒
 * 例如 [1, 2, 3, 4]  ->  [4, 3, 2, 1]
 * ============================================================ */
void reverse_row(int r)
{
    int c, tmp;
    for (c = 0; c < SIZE / 2; c++)   // 只需交换前半和后半对应位置
    {
        tmp = board[r][c];                        // 用临时变量做交换
        board[r][c] = board[r][SIZE - 1 - c];
        board[r][SIZE - 1 - c] = tmp;
    }
}

/* ============================================================
 * transpose：棋盘行列互换（沿主对角线翻转）
 * 例如  1 2          1 3
 *       3 4    ->    2 4
 * 这个技巧让"向上/向下"的移动可以借用"向左"的移动函数
 * ============================================================ */
void transpose()
{
    int r, c, tmp;
    for (r = 0; r < SIZE; r++)
        for (c = r + 1; c < SIZE; c++)   // 只处理对角线以上的格子，避免换两次
        {
            tmp = board[r][c];
            board[r][c] = board[c][r];
            board[c][r] = tmp;
        }
}

/* ============================================================
 * move_right：向右滑动
 * 思路：先把每一行倒过来 -> 向左合并 -> 再倒回去
 * 例如 [2,0,0,2] 倒序变 [2,0,0,2]（左右对称）……
 * 一般例子：[0,2,2,0] -> 倒序 [0,2,2,0] -> 向左合并 [4,0,0,0]
 *          -> 倒序回来 [0,0,0,4]，就相当于向右合并了
 * ============================================================ */
int move_right()
{
    int r, moved;
    for (r = 0; r < SIZE; r++)
        reverse_row(r);        // 每行先倒序
    moved = move_left();       // 调用核心的向左合并
    for (r = 0; r < SIZE; r++)
        reverse_row(r);        // 再倒序回来
    return moved;
}

/* ============================================================
 * move_up：向上滑动
 * 思路：先把棋盘转置 -> 向左合并 -> 再转置回来
 * 转置后，原来的"向上"就变成了"向左"
 * ============================================================ */
int move_up()
{
    int moved;
    transpose();
    moved = move_left();
    transpose();
    return moved;
}

/* ============================================================
 * move_down：向下滑动
 * 思路：先转置 -> 向右合并 -> 再转置回来
 * ============================================================ */
int move_down()
{
    int moved;
    transpose();
    moved = move_right();   // 转置后"向下"变成"向右"
    transpose();
    return moved;
}

/* ============================================================
 * game_over：判断游戏是否结束
 * 返回 1 = 结束；返回 0 = 还能继续玩
 * 结束条件：没有空格，也没有任何相邻相同的数字可以合并
 * ============================================================ */
int game_over()
{
    int r, c;

    /* 情况 1：只要还有空格，就还能放新数字，游戏没结束 */
    for (r = 0; r < SIZE; r++)
        for (c = 0; c < SIZE; c++)
            if (board[r][c] == 0)
                return 0;

    /* 情况 2：没有空格了，检查横向有没有相邻相同的数字 */
    for (r = 0; r < SIZE; r++)
        for (c = 0; c < SIZE - 1; c++)
            if (board[r][c] == board[r][c + 1])
                return 0;

    /* 情况 3：再检查纵向有没有相邻相同的数字 */
    for (r = 0; r < SIZE - 1; r++)
        for (c = 0; c < SIZE; c++)
            if (board[r][c] == board[r + 1][c])
                return 0;

    return 1;   // 三种情况都不成立，真的没救了
}

/* ============================================================
 * has_2048：检查棋盘上是否已经出现 2048
 * 出现就返回 1，否则返回 0
 * ============================================================ */
int has_2048()
{
    int r, c;
    for (r = 0; r < SIZE; r++)
        for (c = 0; c < SIZE; c++)
            if (board[r][c] == TARGET)
                return 1;
    return 0;
}